'use client'
import { useState } from 'react'

const FAQ = [
  { q: 'Для какого возраста подходит урок?', a: 'Бесплатный урок рассчитан на детей 8–17 лет. Программу и сложность преподаватель подбирает под возраст и интересы ребёнка.' },
  { q: 'Нужен ли ребёнку опыт в программировании?', a: 'Нет. Урок подходит для полных новичков — больше половины детей приходят без какого-либо опыта в ИТ.' },
  { q: 'Урок действительно бесплатный?', a: 'Да, урок полностью бесплатный и ни к чему не обязывает. Это знакомство с направлениями и профориентация для ребёнка.' },
  { q: 'Как проходит урок и сколько длится?', a: 'Урок проходит онлайн с преподавателем и длится около 60 минут. Ребёнок сразу делает свой первый проект.' },
  { q: 'Что нужно для участия?', a: 'Достаточно компьютера или ноутбука с интернетом. Все программы бесплатные — ссылки и инструкцию пришлём заранее.' },
  { q: 'Какой результат получит ребёнок после урока?', a: 'Готовый мини-проект (игру, сайт или программу) и понимание, какое направление ему ближе. Родитель получает обратную связь от преподавателя.' },
]

export function Faq() {
  const [open, setOpen] = useState<number>(0)
  return (
    <section>
      <div className="wrap faq">
        <div className="eyebrow">Ответы на вопросы</div>
        <h2>Часто задаваемые вопросы</h2>
        {FAQ.map((item, i) => (
          <div className={`faq-item${open === i ? ' open' : ''}`} key={i}>
            <div className="faq-q" onClick={() => setOpen(open === i ? -1 : i)}>
              {item.q} <span className="pl">+</span>
            </div>
            <div className="faq-a">{item.a}</div>
          </div>
        ))}
      </div>
    </section>
  )
}
